// Counts every food entry across the built-in data modules and writes
// src/data/foodCount.js. Runs automatically before dev/build (see package.json)
// so the landing page stat always matches the real database size — without
// pulling the multi-MB food data chunk into the landing bundle.
import fs from 'fs'
import path from 'path'
import { fileURLToPath } from 'url'

const dataDir = path.join(path.dirname(fileURLToPath(import.meta.url)), '../src/data')

let count = 0
for (const f of fs.readdirSync(dataDir)) {
  if (!/^foods.*\.js$/.test(f)) continue
  const src = fs.readFileSync(path.join(dataDir, f), 'utf8')
  count += (src.match(/\{\s*"?id"?\s*:/g) || []).length
}

const out = `// AUTO-GENERATED by scripts/gen-food-count.mjs — do not edit by hand.
// Regenerated on every dev/build run.
export const FOOD_COUNT = ${count}
`
fs.writeFileSync(path.join(dataDir, 'foodCount.js'), out)
console.log(`foodCount.js written: ${count} foods`)
